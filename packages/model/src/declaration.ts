import { dirname, isAbsolute, relative, sep } from 'node:path'
import type { ModuleFile } from '@ainess/loader'
import { toJavaScriptPath } from './files.js'
import { writeGeneratedFile } from './generated-file.js'

const header = '// Generated by @ainess/model/typegen.\n'

function toModuleSpecifier(directory: string, filename: string): string {
  const path = relative(directory, filename)
  if (isAbsolute(path)) throw new Error(`Cannot reference Model source on another volume: ${filename}`)
  const specifier = toJavaScriptPath(path.split(sep).join('/'))
  return specifier.startsWith('../') ? specifier : `./${specifier}`
}

export async function writeModelDeclaration(target: string, files: readonly ModuleFile[]): Promise<string> {
  const targetDirectory = dirname(target)
  const definitions = files.map(({ absolutePath }) => {
    const specifier = JSON.stringify(toModuleSpecifier(targetDirectory, absolutePath))
    return `  | TypedModel<typeof import(${specifier})>`
  }).join('\n')

  const declaration = `${header}import type {
  InferModel,
  ModelDefinition,
  ModelOperationDefinition,
} from '@ainess/model'

type DefinitionShape = ModelDefinition<string, Readonly<Record<string, ModelOperationDefinition>>>
// A CommonJS export assignment is represented as the exported value.
type TypedModel<
  Module extends DefinitionShape | { default: DefinitionShape },
  Definition = Module extends { default: infer Value } ? Value : Module,
> = unknown extends Module ? never
  : Definition extends DefinitionShape
    ? string extends Definition['name'] ? never : Definition
    : never

type ModelDefinitions =${definitions ? `\n${definitions}` : ' never'}
type GeneratedModelTypes = {
  [Definition in ModelDefinitions as Definition['name']]: InferModel<Definition>
}

declare module '@ainess/model' {
  interface ModelTypes extends GeneratedModelTypes {}
}
`

  await writeGeneratedFile(target, declaration, header)
  return declaration
}
